'use strict';

const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('w2g', {
  getSettings: () => ipcRenderer.invoke('settings:get'),
  saveSettings: (patch) => ipcRenderer.invoke('settings:save', patch),
  checkEnv: () => ipcRenderer.invoke('env:check'),
  installMpv: () => ipcRenderer.invoke('mpv:install'),
  browseMpv: () => ipcRenderer.invoke('mpv:browse'),
  pickFile: (title) => ipcRenderer.invoke('file:pick', title),
  /** Info about a file dropped on the window (Electron no longer exposes File.path). */
  droppedFile: (file) => ipcRenderer.invoke('file:info', webUtils.getPathForFile(file)),
  host: (opts) => ipcRenderer.invoke('host:start', opts),
  changeVideo: (filePath) => ipcRenderer.invoke('host:change', filePath),
  join: (opts) => ipcRenderer.invoke('join', opts),
  cmd: (action, position) => ipcRenderer.invoke('session:cmd', { action, position }),
  chat: (text) => ipcRenderer.invoke('session:chat', text),
  reopenPlayer: () => ipcRenderer.invoke('player:reopen'),
  leave: () => ipcRenderer.invoke('session:leave'),
  copy: (text) => ipcRenderer.invoke('clipboard:write', text),
  openExternal: (url) => ipcRenderer.invoke('open:external', url),
  onUpdate: (cb) => ipcRenderer.on('update', (_e, u) => cb(u)),
  appVersion: () => ipcRenderer.invoke('app:version'),
  checkUpdates: () => ipcRenderer.invoke('app:checkUpdates'),
  whatsNew: () => ipcRenderer.invoke('app:whatsNew'),
  installUpdate: (voice) => ipcRenderer.invoke('app:installUpdate', voice),
  resumeInfo: () => ipcRenderer.invoke('app:resume'),
  onAppUpdate: (cb) => ipcRenderer.on('app-update', (_e, u) => cb(u)),
  voiceSend: (msg) => ipcRenderer.invoke('voice:send', msg),
  onVoice: (cb) => ipcRenderer.on('voice', (_e, msg) => cb(msg)),
  voiceAudio: (bytes) => ipcRenderer.send('voice:audio', bytes),
  voiceWasm: (name) => ipcRenderer.invoke('voice:wasm', name),
  hotkeysSet: (bindings, enabled) => ipcRenderer.invoke('hotkeys:set', bindings, enabled),
  hotkeyCapture: () => ipcRenderer.invoke('hotkeys:capture'),
  hotkeyCancel: () => ipcRenderer.invoke('hotkeys:cancel'),
  onHotkey: (cb) => ipcRenderer.on('hotkey', (_e, h) => cb(h)),
  duck: (level) => ipcRenderer.invoke('player:duck', level),
  videoRect: (rect) => ipcRenderer.invoke('video:rect', rect),
  setPlayerMode: (mode) => ipcRenderer.invoke('player:mode', mode),
  fullscreen: (on) => ipcRenderer.invoke('window:fullscreen', on),
  setVolume: (v) => ipcRenderer.invoke('player:volume', v),
  setMute: (on) => ipcRenderer.invoke('player:mute', on),
  onFullscreen: (cb) => ipcRenderer.on('fullscreen', (_e, on) => cb(on)),
  onCursorX: (cb) => ipcRenderer.on('cursor-x', (_e, x) => cb(x)),
  onToggleSidebar: (cb) => ipcRenderer.on('toggle-sidebar', () => cb()),
  onVoiceAudio: (cb) => ipcRenderer.on('voice-audio', (_e, bytes) => cb(bytes)),
  onEnded: (cb) => ipcRenderer.on('ended', (_e, reason) => cb(reason)),
});
